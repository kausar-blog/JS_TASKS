/***

Subtask-1:

Find all the odd numbers from 61 to 100.

 */

let i = 61;
for (i; i <= 100; i++) {
  if (i % 2 !== 0) {
    console.log(i);
  }
}

/***

Subtask-2:

Find all the even numbers from 78 to 98.

 */

let num = 78;
for (num; num <= 98; num++) {
  if (num % 2 === 0) {
    console.log(num);
  }
}

